test('layout move, undo, baseline, export, persistence and mobile controls', async ({ page }) => {
  await page.goto('/')
  await expect(page.getByText('Data loaded', { exact: false })).toBeVisible()
  await page.getByRole('button', { name: 'Layout Lab', exact: true }).click()
  await expect(page.locator('.product-list button')).toHaveCount(100)
  await expect(page.locator('#destination option')).toHaveCount(252)
  await page.locator('.product-list button').first().click()
  const before = await page.locator('.lab-grid dl').innerText()
  await page.locator('#destination').selectOption('R6-07-R3')
  await page.getByRole('button', { name: 'Apply move & recalculate' }).click()
  await expect(page.locator('.lab-grid dd').nth(1)).toHaveText('R6-07-R3')
  await page.getByRole('button', { name: 'Undo last change' }).click()
  await expect(page.locator('.lab-grid dd').nth(1)).not.toHaveText('R6-07-R3')
  expect(before).toContain('Current slot')
  await page.getByRole('button', { name: 'Apply move & recalculate' }).click()
  await expect(page.locator('.lab-grid dd').nth(1)).toHaveText('R6-07-R3')
  await expect(page.locator('canvas, .team-bar, .sidebar')).toHaveCount(0)
  const downloadEvent = page.waitForEvent('download')
  await page.getByRole('button', { name: 'Export player layout' }).click()
  const download = await downloadEvent
  const exportedPath = await download.path()
  expect(exportedPath).toBeTruthy()
  await page.getByRole('button', { name: 'Reset to original' }).click()
  await page.locator('input[type="file"]').setInputFiles(exportedPath!)
  await expect(page.locator('.notice')).toContainText('Imported layout validated')
  await expect(page.locator('.lab-grid dd').nth(1)).toHaveText('R6-07-R3')
  await page.locator('input[type="file"]').setInputFiles({ name: 'invalid.json', mimeType: 'application/json', buffer: Buffer.from('{"fake":"R99"}') })
  await expect(page.locator('.lab-grid dd').nth(1)).toHaveText('R6-07-R3')
  await page.reload()
  await expect(page.getByText('Data loaded', { exact: false })).toBeVisible()
  await page.getByRole('button', { name: 'Layout Lab', exact: true }).click()
  await page.locator('.product-list button').first().click()
  await expect(page.locator('.lab-grid dd').nth(1)).toHaveText('R6-07-R3')
  await page.getByRole('button', { name: 'Digital Twin', exact: true }).click()
  await page.setViewportSize({ width: 390, height: 844 })
  await expect(page.getByRole('button', { name: 'Digital Twin', exact: true })).toBeVisible()
  await expect(page.getByRole('button', { name: 'Start', exact: true })).toBeVisible()
  expect(await page.evaluate(() => document.documentElement.scrollWidth <= window.innerWidth)).toBe(true)
  await page.screenshot({ path: 'artifacts/dashboard-mobile.png', fullPage: true })
})

