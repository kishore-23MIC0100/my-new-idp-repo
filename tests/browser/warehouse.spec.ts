  await page.screenshot({ path: 'artifacts/human-picker-closeup.png', fullPage: true })
  await page.getByRole('button', { name: 'Select picker 2', exact: true }).click()
  await expect(page.locator('.picker-profile')).toContainText('Picker #2')
  await expect(page.getByRole('img', { name: 'Human warehouse picker 2' })).toBeVisible()
  await page.getByRole('button', { name: 'Start', exact: true }).click()
  await page.getByRole('button', { name: 'Pause', exact: true }).click()
