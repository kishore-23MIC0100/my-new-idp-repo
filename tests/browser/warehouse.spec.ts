  expect(new Set(orders.map(text => text.split(' · ')[0])).size).toBe(3)
  await expect(page.getByRole('img', { name: 'Human warehouse picker 1' })).toBeVisible()
  await page.getByRole('button', { name: 'Follow picker', exact: true }).click()
